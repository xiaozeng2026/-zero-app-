/** 剥离空白与中英文标点：容忍「我 想 死」「活不下去……」之类的写法 */
const NOISE = /[\s,.，。、！？!?~～…\-—:：;；"'""''「」（）()【】\[\]{}]/g;

/** 文本归一化：小写 + 去空白标点 */
export function normalizeText(input: string): string {
  return (input ?? "").toLowerCase().replace(NOISE, "");
}

/**
 * 判断文本是否包含自伤 / 轻生意图
 * @returns true 仅表示命中关键词，由调用方决定兜底呈现
 */
export function detectCrisis(input: string): boolean {
  const text = normalizeText(input);
  if (text.length === 0) return false;
  return CRISIS_KEYWORDS.some((word) => text.includes(word));
}
